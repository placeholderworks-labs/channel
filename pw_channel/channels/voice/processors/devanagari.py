_LATIN_WORD_RULE = re.compile(r"[A-Za-z]+")


def to_devanagari(text: str) -> str:
    if not text:
        return text

    def replace(match: re.Match) -> str:
        word = match.group(0)
        mapped = _WORD_MAP.get(word.lower())
        return mapped if mapped else word

    return _LATIN_WORD_RULE.sub(replace, text)
